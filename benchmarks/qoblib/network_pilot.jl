            entry["encoding"] !== nothing
        ])),
    )
end

function _known_incumbent_summary()
    selected_arcs = Set(KNOWN_INCUMBENT["selected_arcs"])
    x_value(arc) = arc in selected_arcs ? 1 : 0
    z_value = KNOWN_INCUMBENT["qoblib_solution_objective"]
    out_degree_feasible =
        all(sum(x_value((i, j)) for j in NODES if i != j) == DEGREE for i in NODES)
    in_degree_feasible =
        all(sum(x_value((i, j)) for i in NODES if i != j) == DEGREE for j in NODES)
    flow_balance_feasible = all(ARCS) do (k, i)
        incoming = sum(_flow_value((k, j, i)) for j in NODES if j != i)
        outgoing = sum(_flow_value((k, i, j)) for j in NODES if j != i && j != k)

        return incoming - outgoing == _demand(k, i) * INTSCALE
    end
    arc_linking_feasible = all(FLOW_KEYS) do key
        _k, i, j = key

        return _flow_value(key) <= SCALED_BIG_M * x_value((i, j))
    end
    aggregate_loads = Dict{Tuple{Int,Int},Int}(
        arc => sum(_flow_value((k, arc[1], arc[2])) for k in NODES if k != arc[2]) for
        arc in ARCS
    )
    max_aggregate_load = maximum(values(aggregate_loads))
    edge_capacity_feasible = all(load -> load <= z_value, values(aggregate_loads))
    source_feasible =
        out_degree_feasible &&
        in_degree_feasible &&
        flow_balance_feasible &&
        arc_linking_feasible &&
        edge_capacity_feasible

    return Dict{String,Any}(
        "source_objective" => z_value,
        "qoblib_solution_objective" => KNOWN_INCUMBENT["qoblib_solution_objective"],
        "source_feasible" => source_feasible,
        "out_degree_feasible" => out_degree_feasible,
        "in_degree_feasible" => in_degree_feasible,
        "flow_balance_feasible" => flow_balance_feasible,
        "arc_linking_feasible" => arc_linking_feasible,
        "edge_capacity_feasible" => edge_capacity_feasible,
        "selected_arcs" => [collect(arc) for arc in KNOWN_INCUMBENT["selected_arcs"]],
        "positive_flow_count" => length(KNOWN_INCUMBENT["positive_flows"]),
        "max_aggregate_edge_load" => max_aggregate_load,
        "matches_qoblib_solution_artifact" =>
            z_value == KNOWN_INCUMBENT["qoblib_solution_objective"] && source_feasible,
    )
end

